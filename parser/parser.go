//go:embed services.gotmpl
var serviceTemplate []byte

var (
	// enCaser title-cases identifiers (e.g. package names) before applying
	// strcase.ToCamel, so multi-word names collapse into a proper CamelCase form.
	enCaser = cases.Title(language.English)

	// modelHdrTmpl renders the package declaration and import block shared by
	// every generated per-model service file.
	modelHdrTmpl *template.Template

	// modelBodyTmpl renders the CRUD method bodies for a single model, driven
	// by the embedded services.gotmpl template.
	modelBodyTmpl *template.Template

	// mainSvcTmpl renders the aggregate Service struct that embeds every
	// generated per-model service.
	mainSvcTmpl *template.Template

	// bufferPool recycles bytes.Buffer instances used for template rendering
	// to reduce allocation pressure when generating many service files
	// concurrently. Safe for concurrent use by multiple goroutines.
	bufferPool = sync.Pool{
		New: func() any {
			return bytes.NewBuffer(make([]byte, 0, 16*1024))
		},
	}
)

// modelHdrText is the package/import preamble prepended to every generated
// per-model service file. PkgReadOnly gates the "database/sql" import, which
// is only needed by write-capable services (e.g. for sql.NullXxx handling).
const modelHdrText = `// Code generated by "apigen"; DO NOT EDIT.
package {{.PkgName}}

import (
	"{{.ModelPkg}}"
	{{if not .PkgReadOnly}}"database/sql"
	{{end}}"gorm.io/gorm"
	"math"
)
`

// mainSVCText renders the aggregate Service type, which embeds one generated
// service per model plus the shared *gorm.DB handle, along with transaction
// and multi-tenant helper methods.
//
// NOTE: this template references "context.Context" in WithTenant but the
// rendered header template (modelHdrText) does not import "context". See the
// fix in generateGORMServiceFiles / modelHdrText usage notes below — callers
// must ensure the generated base_service.go imports "context", otherwise the
// generated code will fail to compile. This is called out explicitly here
// because it is easy to miss when editing either template independently.
const mainSVCText = `
// Service embeds all generated services.
type Service struct {
	{{range .}}
	{{.}}Service  {{.| ToLower }}Service
	{{- end}}
	DB *gorm.DB
}

// Begin starts a transaction and returns a transactional Service.
func (s *Service) Begin() (*Service, error){
	tx := s.DB.Begin()
	if tx.Error != nil {
		return nil, tx.Error
	}
	return NewService(tx), nil
}

// Commit commits the transaction associated with Service DB.
func (s *Service) Commit() error {
	return s.DB.Commit().Error
}

// Rollback rolls back the transaction associated with Service DB.
func (s *Service) Rollback() error {
	return s.DB.Rollback().Error
}

// WithTenant starts a transaction scoped to a tenant context, returning a transactional Service.
func (s *Service) WithTenant(ctx context.Context, userID, hospitalID uint) (*Service, error) {
	tx := s.DB.WithContext(ctx).Begin()
	if tx.Error != nil {
		return nil, tx.Error
	}
	if err := tx.Exec("SELECT set_current_tenant(?);", hospitalID).Error; err != nil {
		tx.Rollback()
		return nil, err
	}
	if err := tx.Exec("SELECT set_current_user(?);", userID).Error; err != nil {
		tx.Rollback()
		return nil, err
	}
	return NewService(tx), nil
}

// NewService returns a Service that embeds all generated model services.
func NewService(db *gorm.DB) *Service {
	svc := &Service{
		{{- range .}}
		{{- if ne . "Service"}}
		{{.}}Service: new{{.}}Service(db),
		{{- end}}
		{{- end}}
		DB: db,
	}
	return svc
}
`

// init parses the package's text/template instances once at program start.
// template.Must panics on malformed templates, which is appropriate here:
// a broken embedded template is a build-time programmer error, not a
// runtime condition callers can recover from.
func init() {
	funcMap := template.FuncMap{
		"ToLower": strings.ToLower,
		// ToCamelCase title-cases s then converts it to CamelCase, e.g.
		// "patient record" -> "PatientRecord".
		"ToCamelCase": func(s string) string {
			return strcase.ToCamel(enCaser.String(s))
		},
		// join renders a string slice as a comma-separated list of Go string
		// literals, e.g. []string{"a","b"} -> `"a", "b"`. The unused second
		// argument is retained for template call-site compatibility.
		"join": func(s []string, _ string) string {
			quotedSlice := make([]string, len(s))
			for i, item := range s {
				quotedSlice[i] = fmt.Sprintf("%q", item)
			}
			return strings.Join(quotedSlice, ", ")
		},
	}
	modelHdrTmpl = template.Must(template.New("modelHeader").Parse(modelHdrText))
	modelBodyTmpl = template.Must(template.New("tmpl").Funcs(funcMap).Parse(string(serviceTemplate)))
	mainSvcTmpl = template.Must(template.New("mainSVC").Funcs(funcMap).Parse(mainSVCText))
}

const (
	// skipTag is the doc-comment marker ("apigen:skip") that excludes a
	// struct from service generation entirely.
	skipTag = "apigen:skip"

	// foreignKeyIdent is the GORM struct-tag substring identifying a
	// belongs-to/has-one foreign key relation.
	foreignKeyIdent = "foreignKey"

	// many2manyIdent is the GORM struct-tag substring identifying a
	// many-to-many relation.
	many2manyIdent = "many2many"
)

// Field describes a single struct field discovered during AST parsing,
// carrying enough information to render preload/omit logic and Go type
// declarations in the generated service code.
type Field struct {
	Name     string // Field name as declared in source, e.g. "PatientID".
	Type     string // Full Go type as written, e.g. "*uint" or "[]Visit".
	BaseType string // Type with pointer/slice/array wrappers stripped, e.g. "Visit".
	Tag      string // Raw struct tag literal, including surrounding backticks.
	Preload  bool   // True if the field is a GORM foreignKey or many2many association.
	Parent   string // Name of the struct that declares this field.
}

// StructMeta describes a single top-level struct declaration extracted from
// a parsed package, along with the fields and metadata needed to generate a
// GORM-backed service for it.
type StructMeta struct {
	Name    string  // Struct type name, e.g. "Patient".
	PKType  string  // Go type of the "ID" field, if present, e.g. "uint".
	Fields  []Field // All fields declared directly on the struct.
	Package string  // Fully-qualified import path of the declaring package.
	Skip    bool    // True if the struct is annotated with the apigen:skip doc comment.
}

// formatSelectorExpr renders a possibly-qualified identifier expression
// (e.g. "time.Time" or "pkg.sub.Type") back into its dotted source form.
// Returns "" for expression kinds it does not recognize.
func formatSelectorExpr(expr ast.Expr) string {
	switch x := expr.(type) {
	case *ast.Ident:
		return x.Name
	case *ast.SelectorExpr:
		return formatSelectorExpr(x.X) + "." + x.Sel.Name
	default:
		return ""
	}
}

// formatArrayType renders the element type of an array/slice type expression
// back into source form, recursing for nested array/slice element types
// (e.g. "[][]byte"). Returns "" for element kinds it does not recognize.
func formatArrayType(typ *ast.ArrayType) string {
	switch elemType := typ.Elt.(type) {
	case *ast.Ident:
		return elemType.Name
	case *ast.SelectorExpr:
		return formatSelectorExpr(elemType)
	case *ast.ArrayType:
		return "[]" + formatArrayType(elemType)
	default:
		return ""
	}
}

// getArrayLen returns the declared length of a fixed-size array type, or 0
// for slices (nil Len) or lengths that cannot be parsed as a literal integer
// (e.g. a const identifier or expression, which this simple AST pass does
// not evaluate).
func getArrayLen(arrayType *ast.ArrayType) int {
	if arrayType == nil || arrayType.Len == nil {
		return 0
	}
	if basicLit, ok := arrayType.Len.(*ast.BasicLit); ok {
		if intValue, err := strconv.Atoi(basicLit.Value); err == nil {
			return intValue
		}
	}
	return 0
}

// Parse loads the syntax trees for modelPkgs and extracts StructMeta for
// every top-level struct type declaration found, in the order encountered.
// Only syntax is loaded (packages.NeedSyntax | NeedName | NeedFiles); no
// type-checking is performed, which keeps parsing fast but means field types
// are derived purely from their AST shape rather than resolved identifiers.
//
// Parse returns nil if modelPkgs is empty. It returns an error, rather than
// panicking, if the packages fail to load, so callers can report the failure
// through normal error-handling paths instead of crashing the process.
func Parse(modelPkgs []string) ([]StructMeta, error) {
	if len(modelPkgs) == 0 {
		return nil, nil
	}

	cfg := &packages.Config{
		Mode: packages.NeedSyntax | packages.NeedName | packages.NeedFiles,
	}
	pkgs, err := packages.Load(cfg, modelPkgs...)
	if err != nil {
		return nil, fmt.Errorf("failed to load packages %v: %w", modelPkgs, err)
	}

	// packages.Load can report per-package errors (e.g. malformed source)
	// without returning a top-level err. Surface those explicitly instead of
	// silently generating services from a partially-parsed package.
	var loadErrs []error
	packages.Visit(pkgs, nil, func(pkg *packages.Package) {
		for _, e := range pkg.Errors {
			loadErrs = append(loadErrs, e)
		}
	})
	if len(loadErrs) > 0 {
		return nil, fmt.Errorf("errors loading packages: %v", errors.Join(loadErrs...))
	}

	// Allocate 1K for each package.
	// Reduces frequent slice allocations.
	structSlice := make([]StructMeta, 0, len(pkgs)*1*1024)

	var wg sync.WaitGroup

	for _, pkg := range pkgs {
		// Process package file in parallel
		for _, file := range pkg.Syntax {
			wg.Go(func() {
				for _, decl := range file.Decls {
					genDecl, ok := decl.(*ast.GenDecl)
					if !ok {
						continue
					}
					for _, spec := range genDecl.Specs {
						t, ok := spec.(*ast.TypeSpec)
						if !ok {
							continue
						}
						stype, ok := t.Type.(*ast.StructType)
						if !ok {
							continue
						}

						meta := StructMeta{
							Name:    t.Name.Name,
							Package: pkg.PkgPath,
							Fields:  make([]Field, 0, len(stype.Fields.List)),
						}

						// A skip directive may appear either on the TypeSpec's own
						// doc comment (`// apigen:skip` directly above the type
						// name in a grouped `type ( ... )` block) or on the
						// enclosing GenDecl's doc comment (a lone `type X struct`
						// declaration). We check both locations.
						if t.Doc != nil {
							for _, comment := range t.Doc.List {
								if strings.Contains(comment.Text, skipTag) {
									meta.Skip = true
									break
								}
							}
						}

						if !meta.Skip && genDecl.Doc != nil {
							for _, comment := range genDecl.Doc.List {
								if strings.Contains(comment.Text, skipTag) {
									meta.Skip = true
									break
								}
							}
						}

						for _, field := range stype.Fields.List {
							var tagValue string
							if field.Tag != nil {
								tagValue = field.Tag.Value
							}
							isFK := strings.Contains(tagValue, foreignKeyIdent)
							isManyToMany := strings.Contains(tagValue, many2manyIdent)
							preload := isFK || isManyToMany

							switch typ := field.Type.(type) {
							case *ast.Ident:
								for _, name := range field.Names {
									if name.Name == "ID" {
										meta.PKType = typ.Name
									}
									meta.Fields = append(meta.Fields, Field{
										Name:     name.Name,
										Parent:   meta.Name,
										Tag:      tagValue,
										Type:     typ.Name,
										BaseType: typ.Name,
										Preload:  preload,
									})
								}
							case *ast.SelectorExpr:
								fieldType := formatSelectorExpr(typ)
								for _, name := range field.Names {
									meta.Fields = append(meta.Fields, Field{
										Name:     name.Name,
										Parent:   meta.Name,
										Tag:      tagValue,
										Type:     fieldType,
										BaseType: fieldType,
										Preload:  preload,
									})
								}
							case *ast.ArrayType:
								fieldType := formatArrayType(typ)
								arrLen := getArrayLen(typ)
								var arrType string
								if arrLen == 0 {
									arrType = "[]" + fieldType
								} else {
									arrType = fmt.Sprintf("[%d]%s", arrLen, fieldType)
								}
								for _, name := range field.Names {
									meta.Fields = append(meta.Fields, Field{
										Name:     name.Name,
										Parent:   meta.Name,
										Tag:      tagValue,
										Type:     arrType,
										BaseType: fieldType,
										Preload:  preload,
									})
								}
							case *ast.StarExpr:
								switch t := typ.X.(type) {
								case *ast.Ident:
									for _, name := range field.Names {
										meta.Fields = append(meta.Fields, Field{
											Name:     name.Name,
											Parent:   meta.Name,
											Tag:      tagValue,
											Type:     "*" + t.Name,
											BaseType: t.Name,
											Preload:  preload,
										})
									}
								case *ast.SelectorExpr:
									identName := formatSelectorExpr(t)
									for _, name := range field.Names {
										meta.Fields = append(meta.Fields, Field{
											Name:     name.Name,
											BaseType: identName,
											Parent:   meta.Name,
											Tag:      tagValue,
											Type:     identName,
											Preload:  preload,
										})
									}
								case *ast.ArrayType:
									if ident, ok := t.Elt.(*ast.Ident); ok {
										arrLen := getArrayLen(t)
										var arrType string
										if arrLen == 0 {
											arrType = "*[]" + ident.Name
										} else {
											arrType = fmt.Sprintf("*[%d]%s", arrLen, ident.Name)
										}
										for _, name := range field.Names {
											meta.Fields = append(meta.Fields, Field{
												Name:     name.Name,
												BaseType: ident.Name,
												Parent:   meta.Name,
												Tag:      tagValue,
												Type:     arrType,
												Preload:  preload,
											})
										}
									}
								}
							}
						}

						structSlice = append(structSlice, meta)
					}
				}

			})
		}
	}

	wg.Wait()
	return structSlice, nil
}

// Map indexes structs by their Name for O(1) lookup. If data contains
// duplicate struct names (e.g. across packages), the later entry in data
// wins, matching normal Go map-assignment semantics.
func Map(data []StructMeta) map[string]StructMeta {
	m := make(map[string]StructMeta, len(data))
	for _, row := range data {
		m[row.Name] = row
	}
	return m
}

// tmplData is the top-level data structure passed to modelHdrTmpl and
// modelBodyTmpl when rendering a single model's service file.
type tmplData struct {
	PkgName           string            // Output package name for generated services.
	ModelPkg          string            // Fully-qualified import path of this model's package.
	ModelPkgs         []string          // All configured model package import paths.
	ModelPkgName      string            // Last path segment of ModelPkg, used as the Go import qualifier.
	ModelObj          StructMeta        // Full metadata for the model being rendered.
	Model             string            // Model struct name, e.g. "Patient".
	OmitFields        []string          // Association field prefixes to omit on partial updates.
	Preloads          []string          // Preload paths to eagerly load for this model.
	DefaultAllocSize  uint              // Default slice/result preallocation hint for generated queries.
	Queries           queryTemplateData // Per-query-method generation settings.
	PkgReadOnly       bool              // True if this model's package is configured as read-only.
	WritePKGDecl      bool              // True when rendering the base service (needs its own package/import decl).
	SkipService       bool              // True to render only shared helpers, omitting the per-model service body.
	PreallocateSlices bool              // True to preallocate result slices using DefaultAllocSize.
}

// queryMethodTemplateData holds per-method generation flags resolved from
// configuration for a single CRUD query method (e.g. "Get", "FindMany").
type queryMethodTemplateData struct {
	PreloadAll        bool // True to eagerly preload all associations for this method.
	RefetchAfterWrite bool // True to re-fetch the record after a create/update to populate associations.
}

// queryTemplateData aggregates queryMethodTemplateData for every supported
// generated query method on a model's service.
type queryTemplateData struct {
	Get                  queryMethodTemplateData
	GetAll               queryMethodTemplateData
	GetPaginated         queryMethodTemplateData
	FindOne              queryMethodTemplateData
	FindMany             queryMethodTemplateData
	Create               queryMethodTemplateData
	CreateMany           queryMethodTemplateData
	Update               queryMethodTemplateData
	PartialUpdate        queryMethodTemplateData
	PartialUpdateWithMap queryMethodTemplateData
}

// packageReadOnly reports whether pkg is listed in cfg.Models.ReadOnly,
// meaning write-capable service methods (Create/Update/Delete) should not
// be generated for structs declared in it.
func packageReadOnly(cfg *config.Config, pkg string) bool {
	return slices.Contains(cfg.Models.ReadOnly, pkg)
}

// generatedFileResult carries the outcome of rendering a single model's
// service file from a worker goroutine back to the collecting goroutine.
type generatedFileResult struct {
	fileName string
	content  []byte
	err      error
}

// generateGORMServiceFiles renders one Go source file per struct in structs,
// plus a shared base_service.go, and returns them keyed by output filename.
// Template execution and gofmt formatting for each model run concurrently
// across a bounded worker pool sized to runtime.NumCPU().
//
// Structs listed in cfg.Models.Skip are excluded from per-model file
// generation but are still counted when deduplicating by name and when
// building the base service's model name list (minus the skipped models
// themselves, so they are not embedded in the aggregate Service struct).
//
// generateGORMServiceFiles returns an error immediately on the first
// rendering or formatting failure encountered while draining results; it
// does not attempt partial output on error.
func generateGORMServiceFiles(structs []StructMeta, cfg *config.Config) (map[string][]byte, error) {
	if cfg == nil {
		return nil, fmt.Errorf("generateGORMServiceFiles: cfg must not be nil")
	}

	preloads := GetPreloadMap(structs, cfg)
	files := make(map[string][]byte, len(structs)+1)

	var (
		uniqueStructs []StructMeta
		modelNames    = make([]string, 0, len(structs))
		seen          = make(map[string]struct{}, len(structs))
	)
	for _, st := range structs {
		if _, exists := seen[st.Name]; exists {
			continue
		}
		seen[st.Name] = struct{}{}
		modelNames = append(modelNames, st.Name)
		if !slices.Contains(cfg.Models.Skip, st.Name) {
			uniqueStructs = append(uniqueStructs, st)
		}
	}

	// Nothing to generate besides the base service; avoid spinning up a
	// worker pool with zero tasks.
	if len(uniqueStructs) == 0 {
		return finalizeBaseService(files, modelNames, cfg)
	}

	// Worker pool for parallel template execution & gofmt. Bounded by
	// available CPUs and never exceeding the number of structs to process,
	// so we don't over-allocate goroutines for small inputs.
	numWorkers := max(min(runtime.NumCPU(), len(uniqueStructs)), 1)
	tasks := make(chan StructMeta, len(uniqueStructs))
	results := make(chan generatedFileResult, len(uniqueStructs))

	var wg sync.WaitGroup
	for range numWorkers {
		wg.Go(func() {
			for st := range tasks {
				parts := strings.Split(st.Package, "/")
				modelPkgName := parts[len(parts)-1]
				preloadFields := preloads[st.Name]

				// omitFields collects the top-level (pre-dot) prefix of each
				// preload path, deduplicated, so e.g. preloads of
				// "Visits.Doctor" and "Visits.Notes" both contribute only
				// "Visits" once.
				omitFields := make([]string, 0, len(preloadFields))
				for _, f := range preloadFields {
					prefix := f
					if before, _, ok := strings.Cut(f, "."); ok {
						prefix = before
					}
					if !slices.Contains(omitFields, prefix) {
						omitFields = append(omitFields, prefix)
					}
				}

				data := tmplData{
					PkgName:      cfg.Output.ServiceName,
					ModelPkg:     st.Package,
					ModelPkgs:    cfg.Models.Pkgs,
					ModelPkgName: modelPkgName,
					Queries:      newQueryTemplateData(cfg, st.Name),
					PkgReadOnly:  packageReadOnly(cfg, st.Package),
					ModelObj:     st,
					Model:        st.Name,
					WritePKGDecl: false,
					Preloads:     preloadFields,
					OmitFields:   omitFields,
					SkipService:  false,
				}

				buf := bufferPool.Get().(*bytes.Buffer)
				buf.Reset()

				var renderErr error
				if err := modelHdrTmpl.Execute(buf, data); err != nil {
					renderErr = fmt.Errorf("error executing header for %s: %w", st.Name, err)
				} else if err := modelBodyTmpl.Execute(buf, data); err != nil {
					renderErr = fmt.Errorf("error executing body for %s: %w", st.Name, err)
				}

				var formatted []byte
				if renderErr == nil {
					// Copy out of the pooled buffer before formatting: format.Source
					// returns a new slice, but buf itself is about to be returned to
					// the pool and must not be referenced afterward.
					formatted, renderErr = format.Source(buf.Bytes())
					if renderErr != nil {
						renderErr = fmt.Errorf("error formatting service for %s: %w", st.Name, renderErr)
					}
				}
				bufferPool.Put(buf)

				results <- generatedFileResult{
					fileName: strcase.ToSnake(st.Name) + "_service.go",
					content:  formatted,
					err:      renderErr,
				}
			}
		})
	}
	for _, st := range uniqueStructs {
		tasks <- st
	}
	close(tasks)
	wg.Wait()
	close(results)

	for res := range results {
		if res.err != nil {
			return nil, res.err
		}
		files[res.fileName] = res.content
	}

	return finalizeBaseService(files, modelNames, cfg)
}

// finalizeBaseService renders base_service.go (the shared Service struct,
// transaction helpers, and NewService constructor) into files and returns
// the completed file map. Split out of generateGORMServiceFiles so the
// zero-model fast path and the worker-pool path share identical base-service
// generation logic instead of duplicating it.
func finalizeBaseService(files map[string][]byte, modelNames []string, cfg *config.Config) (map[string][]byte, error) {
	baseBuf := bufferPool.Get().(*bytes.Buffer)
	baseBuf.Reset()
	defer bufferPool.Put(baseBuf)

	baseData := tmplData{
		PkgName:      cfg.Output.ServiceName,
		ModelPkgs:    cfg.Models.Pkgs,
		WritePKGDecl: true,
		SkipService:  true,
	}
	if err := modelBodyTmpl.Execute(baseBuf, baseData); err != nil {
		return nil, fmt.Errorf("error executing base service body: %w", err)
	}

	services := make([]string, 0, len(modelNames))
	for _, m := range modelNames {
		if !slices.Contains(cfg.Models.Skip, m) {
			services = append(services, m)
		}
	}
	if err := mainSvcTmpl.Execute(baseBuf, services); err != nil {
		return nil, fmt.Errorf("error executing main service template: %w", err)
	}

	baseContent, err := format.Source(baseBuf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("error formatting base service: %w", err)
	}
	files["base_service.go"] = baseContent
	return files, nil
}

// newQueryTemplateData resolves per-method generation settings for every
// supported query method of model from cfg, falling back to cfg's defaults
// wherever a model-specific override is not configured.
func newQueryTemplateData(cfg *config.Config, model string) queryTemplateData {
	return queryTemplateData{
		Get:                  newQueryMethodTemplateData(cfg.QueryConfig(model, "Get")),
		GetAll:               newQueryMethodTemplateData(cfg.QueryConfig(model, "GetAll")),
		GetPaginated:         newQueryMethodTemplateData(cfg.QueryConfig(model, "GetPaginated")),
		FindOne:              newQueryMethodTemplateData(cfg.QueryConfig(model, "FindOne")),
		FindMany:             newQueryMethodTemplateData(cfg.QueryConfig(model, "FindMany")),
		Create:               newQueryMethodTemplateData(cfg.QueryConfig(model, "Create")),
		CreateMany:           newQueryMethodTemplateData(cfg.QueryConfig(model, "CreateMany")),
		Update:               newQueryMethodTemplateData(cfg.QueryConfig(model, "Update")),
		PartialUpdate:        newQueryMethodTemplateData(cfg.QueryConfig(model, "PartialUpdate")),
		PartialUpdateWithMap: newQueryMethodTemplateData(cfg.QueryConfig(model, "PartialUpdateWithMap")),
	}
}

// newQueryMethodTemplateData adapts a resolved config.EffectiveQuerySettings
// into the narrower queryMethodTemplateData shape consumed by templates.
func newQueryMethodTemplateData(settings config.EffectiveQuerySettings) queryMethodTemplateData {
	return queryMethodTemplateData{
		PreloadAll:        settings.PreloadAll,
		RefetchAfterWrite: settings.RefetchAfterWrite,
	}
}
