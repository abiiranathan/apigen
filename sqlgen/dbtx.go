package sqlgen

import (
	"fmt"
	"io"
	"strings"
)

// WriteDBTX writes the DBTX interface to w. Unlike Generate, this is not
// per-model: call it once per output package (e.g. into queries/dbtx.go),
// since every generated function in that package depends on the DBTX type.
func WriteDBTX(w io.Writer) error {
	var b strings.Builder
	b.Grow(1024)

	fmt.Fprintf(&b, "// Code generated by apigen; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "package queries\n\n")
	fmt.Fprintf(&b, "import (\n")
	fmt.Fprintf(&b, "\t\"context\"      // for context.Context\n")
	fmt.Fprintf(&b, "\t\"database/sql\" // for sql.Result, sql.Row, sql.Rows\n")
	fmt.Fprintf(&b, ")\n\n")

	fmt.Fprintf(&b, "// DBTX is the minimal subset of *sql.DB used by generated query functions.\n")
	fmt.Fprintf(&b, "// *sql.DB and *sql.Tx both satisfy it natively, so any generated function\n")
	fmt.Fprintf(&b, "// can be called either standalone or inside a transaction by passing a\n")
	fmt.Fprintf(&b, "// *sql.Tx in place of the pool.\n")
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// Implementations must be safe for concurrent use by multiple goroutines,\n")
	fmt.Fprintf(&b, "// matching the contract of *sql.DB and *sql.Tx.\n")
	fmt.Fprintf(&b, "type DBTX interface {\n")
	fmt.Fprintf(&b, "\tExecContext(ctx context.Context, query string, args ...any) (sql.Result, error)\n")
	fmt.Fprintf(&b, "\tQueryContext(ctx context.Context, query string, args ...any) (*sql.Rows, error)\n")
	fmt.Fprintf(&b, "\tQueryRowContext(ctx context.Context, query string, args ...any) *sql.Row\n")
	fmt.Fprintf(&b, "}\n")

	if _, err := io.WriteString(w, b.String()); err != nil {
		return fmt.Errorf("sqlgen: failed to write dbtx.go: %w", err)
	}
	return nil
}
